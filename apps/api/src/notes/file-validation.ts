import { NOTE_LIMITS, type NoteFileType } from "@copilot/shared";
import { AppError } from "../errors.js";

/** A rejected upload. The message is safe and written for the student. */
export class NoteFileError extends AppError {
  constructor(status: 400 | 413 | 415, code: string, message: string) {
    super(status, code, message);
    this.name = "NoteFileError";
  }
}

const EXTENSIONS: Record<string, NoteFileType> = { pdf: "pdf", txt: "txt", md: "md", markdown: "md" };
const MIME: Record<NoteFileType, string> = { pdf: "application/pdf", txt: "text/plain", md: "text/markdown" };

/**
 * Reduces a client-supplied filename to a safe display name. It is only ever DISPLAYED: storage
 * paths are generated by the server and never contain any part of it.
 */
export function sanitizeFilename(raw: string | undefined | null): string {
  const base = (raw ?? "").replaceAll("\\", "/").split("/").pop() ?? "";
  const cleaned = base
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f<>:"|?*‪-‮⁦-⁩]/g, "") // controls, reserved chars, bidi overrides
    .replace(/\s+/g, " ")
    .replace(/^\.+/, "")
    .trim()
    .slice(0, 255);
  return cleaned || "untitled";
}

export function extensionOf(filename: string): string {
  const i = filename.lastIndexOf(".");
  return i === -1 ? "" : filename.slice(i + 1).toLowerCase();
}

/** "Quarterly Report_v2.final.pdf" -> "Quarterly Report v2 final". */
export function titleFromFilename(filename: string): string {
  const i = filename.lastIndexOf(".");
  const stem = i > 0 ? filename.slice(0, i) : filename;
  const title = stem.replace(/[_]+/g, " ").replace(/\s+/g, " ").trim();
  return (title || "Untitled").slice(0, NOTE_LIMITS.titleMaxChars);
}

export interface DetectedFile {
  fileType: NoteFileType;
  mime: string;
  /** Decoded text for txt/md (so it is read once). */
  text?: string;
}

const PDF_MAGIC = [0x25, 0x50, 0x44, 0x46, 0x2d]; // "%PDF-"

function hasPdfHeader(bytes: Uint8Array): boolean {
  const head = bytes.subarray(0, Math.min(bytes.length, 1024));
  outer: for (let i = 0; i + PDF_MAGIC.length <= head.length; i++) {
    for (let j = 0; j < PDF_MAGIC.length; j++) if (head[i + j] !== PDF_MAGIC[j]) continue outer;
    return true;
  }
  return false;
}

/** Strict UTF-8 decoding of a text file. Throws NoteFileError if it is not plain readable text. */
export function decodeTextFile(bytes: Uint8Array): string {
  if (bytes.includes(0)) {
    throw new NoteFileError(400, "invalid_file", "This looks like a binary file, not plain text.");
  }
  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    throw new NoteFileError(400, "invalid_file", "This text file is not valid UTF-8. Save it as UTF-8 and try again.");
  }
  text = text.replace(/^﻿/, "");
  // A text file that is mostly control characters is not a study document.
  // eslint-disable-next-line no-control-regex
  const controls = text.match(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g)?.length ?? 0;
  if (text.length > 0 && controls / text.length > 0.02) {
    throw new NoteFileError(400, "invalid_file", "This file does not look like readable text.");
  }
  return text;
}

/**
 * Decides what a file REALLY is from its content, not from the client's MIME type or name alone.
 * The extension must agree with the content (a ".pdf" that is not a PDF is rejected, and so is a
 * PDF renamed ".txt").
 */
export function detectFile(bytes: Uint8Array, filename: string): DetectedFile {
  if (bytes.length === 0) throw new NoteFileError(400, "empty_file", "This file is empty.");
  if (bytes.length > NOTE_LIMITS.maxFileBytes) {
    throw new NoteFileError(413, "file_too_large", `This file is larger than ${NOTE_LIMITS.maxFileBytes / (1024 * 1024)} MB.`);
  }
  const fileType = EXTENSIONS[extensionOf(filename)];
  if (!fileType) {
    throw new NoteFileError(415, "unsupported_type", "Unsupported file type. Upload a PDF, TXT or Markdown file, or paste your text.");
  }
  const looksLikePdf = hasPdfHeader(bytes);
  if (fileType === "pdf") {
    if (!looksLikePdf) throw new NoteFileError(400, "invalid_file", "This file is not a valid PDF (it may be corrupted or renamed).");
    return { fileType, mime: MIME.pdf };
  }
  if (looksLikePdf) throw new NoteFileError(400, "invalid_file", "This is a PDF with a text-file name. Rename it to .pdf and upload it again.");
  const text = decodeTextFile(bytes);
  if (text.trim() === "") throw new NoteFileError(400, "empty_file", "This file contains no text.");
  return { fileType, mime: MIME[fileType], text };
}
